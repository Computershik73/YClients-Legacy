#import <Foundation/Foundation.h>

/**
 * Время в этом приложении — настенное время филиала, и только оно.
 *
 * Это решение, а не упрощение, и стоит объяснить, от чего оно отказывается.
 *
 * Сервер отдаёт запись как `"datetime": "2026-09-04T12:00:00+03:00"`, то есть
 * с поясом филиала. Честный путь — разобрать это в момент времени и показать
 * его в поясе устройства. Но у журнала записей нет ни одного случая, когда
 * это было бы верно: администратор в зале смотрит на сетку, чтобы сказать
 * «приходите к двенадцати», и двенадцать здесь — это двенадцать на стене
 * филиала. Если телефон стоит в другом поясе — а он стоит, стоит вернуться
 * из отпуска и забыть переключить, — честный пересчёт сдвинет **всю** сетку,
 * и записи разъедутся с расписанием сотрудников, которое сервер прислал
 * в тех же настенных часах.
 *
 * Поэтому: из строки берутся год, месяц, день, часы и минуты, а пояс
 * отбрасывается. Дальше они живут как NSDate, построенный в GMT, — GMT взят
 * не потому, что время в GMT, а потому, что это единственный пояс, где
 * нет перевода часов и где 12:00 остаётся двенадцатью при любых настройках
 * устройства. Обратно на сервер уходит та же настенная запись.
 *
 * Отсюда правило: **любой** календарь, форматтер и разбор даты в этом
 * приложении берётся отсюда. NSCalendar.currentCalendar и NSDateFormatter
 * с поясом по умолчанию в коде появляться не должны — они внесут пояс
 * устройства обратно, и разъедется ровно половина показанного.
 */

/** Календарь для всей арифметики дат: григорианский, GMT. */
NSCalendar *YCCalendar(void);

/**
 * Разбирает `datetime` или `date` из ответа сервера.
 *
 * Понимает оба вида, которые встречаются в ответах: `2026-09-04T12:00:00+03:00`
 * и `2026-09-04 12:00:00`. Пояс, если он есть, отбрасывается — см. выше.
 * Возвращает nil, если строка не разобрана.
 */
NSDate *YCDateFromAPI(NSString *string);

/** Дата и время для отправки на сервер: `2026-09-04 12:00:00`. */
NSString *YCAPIFromDate(NSDate *date);

/** Только день, для параметров start_date и end_date: `2026-09-04`. */
NSString *YCDayFromDate(NSDate *date);

/** Полночь того дня, в который попадает date. */
NSDate *YCStartOfDay(NSDate *date);

/** Полночь дня, отстоящего от date на days суток. */
NSDate *YCDayByAdding(NSDate *date, NSInteger days);

/** Сколько секунд прошло с начала суток: 12:30 — это 45000. */
NSTimeInterval YCSecondsIntoDay(NSDate *date);

/** Тот же день, но с указанным числом секунд от полуночи. */
NSDate *YCDateWithSecondsIntoDay(NSDate *day, NSTimeInterval seconds);

/** `12:30` — для подписи на записи и на шкале времени. */
NSString *YCClockFromDate(NSDate *date);

/** `чт, 4 сентября` — заголовок дня. */
NSString *YCTitleFromDate(NSDate *date);

/** `4 сентября` — короткий заголовок в панели журнала. */
NSString *YCShortTitleFromDate(NSDate *date);

/** `4 сентября 2026` — заголовок карточки записи. */
NSString *YCLongTitleFromDate(NSDate *date);

/** `Сентябрь` — заголовок месяца в календаре. */
NSString *YCMonthTitleFromDate(NSDate *date);

/** `4 сентября 2026, 14:30` — строка «Дата и время» в форме. */
NSString *YCDateTimeFromDate(NSDate *date);

/** Один и тот же ли это календарный день. */
BOOL YCSameDay(NSDate *a, NSDate *b);
