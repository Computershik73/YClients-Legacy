#import <Foundation/Foundation.h>

/**
 * Пояснение сервера к последнему отказу.
 *
 * Библиотека cYclients возвращает наружу только код ответа HTTP, и этого
 * мало ровно там, где важнее всего: при сохранении записи сервер отвечает
 * одним и тем же кодом на «это время занято», «нет прав на чужую запись»
 * и «телефон не того формата», а разницу пишет в поле meta.message.
 *
 * Показать в интерфейсе «не удалось сохранить» вместо «на это время уже
 * есть запись» — значит заставить пользователя гадать. Поэтому транспорт
 * запоминает последнее пояснение здесь, а YCApi забирает его сразу после
 * неуспешного вызова.
 *
 * Значение живёт до следующего запроса. Это безопасно только потому, что
 * все вызовы библиотеки идут через одну последовательную очередь YCApi:
 * второго запроса, который затёр бы чужое пояснение, просто не бывает.
 * Читать отсюда с главного потока нельзя — там уже может лежать пояснение
 * от следующего запроса.
 */
NSString *YCTransportLastMessage(void);

/** Забыть прошлое пояснение. Зовётся перед каждым вызовом библиотеки. */
void YCTransportResetLastMessage(void);
